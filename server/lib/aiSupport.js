// تاریخچه‌ی سمت کلاینت قابل اعتماد نیست؛ نقش‌ها و طول را اینجا محدود می‌کنیم
const MAX_TURNS = 8; // حداکثر ۸ پیام آخرِ کاربر
const MAX_USER_CHARS = 1500;

function sanitizeHistory(history) {
  if (!Array.isArray(history)) return [];
  const clean = [];
  for (const m of history) {
    if (!m || typeof m !== "object") continue;
    const role = m.role === "assistant" ? "assistant" : m.role === "user" ? "user" : null;
    if (!role) continue;
    const content = String(m.content ?? "").trim().slice(0, MAX_USER_CHARS);
    if (!content) continue;
    clean.push({ role, content });
  }
  // فقط آخرین نوبت‌ها و با شروع از user
  const tail = clean.slice(-MAX_TURNS * 2);
  while (tail.length && tail[0].role !== "user") tail.shift();
  return tail;
}

/**
 * گفتگو با دستیار پشتیبانی.
 * @param {{message?:string, history?:Array}} input
 * @returns {Promise<{reply:string}>}
 */
export async function supportChat({ message = "", history = [] } = {}) {
  if (!aiConfigured()) {
    const err = new Error("پشتیبانی هوشمند در حال حاضر فعال نیست.");
    err.status = 503;
    throw err;
  }
  const userMessage = String(message ?? "").trim().slice(0, MAX_USER_CHARS);
  if (!userMessage) {
    const err = new Error("متن پرسش را بنویسید.");
    err.status = 400;
    throw err;
  }

  const messages = [
    { role: "system", content: systemPrompt() },
    ...sanitizeHistory(history),
    { role: "user", content: userMessage },
  ];

  const baseUrl = (process.env.CHABOKAN_AI_BASE_URL || DEFAULT_BASE_URL).replace(/\/+$/, "");
  const controller = new AbortController();
  const timeoutMs = Number(process.env.CHABOKAN_AI_TIMEOUT_MS || "30000");
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  let res;
  try {
    res = await fetch(`${baseUrl}/chat/completions`, {
      method: "POST",
      signal: controller.signal,
      headers: {
        Authorization: `Bearer ${process.env.CHABOKAN_AI_API_KEY.trim()}`,
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      body: JSON.stringify({
        model: aiModel(),
        messages,
        temperature: Number(process.env.CHABOKAN_AI_TEMPERATURE || "0.3"),
        max_tokens: 700,
      }),
    });
  } catch (err) {
    clearTimeout(timer);
    if (err?.name === "AbortError") {
      const e = new Error("پاسخ دستیار طول کشید؛ دوباره تلاش کنید.");
      e.status = 504;
      throw e;
    }
    const e = new Error("ارتباط با سرویس هوش مصنوعی برقرار نشد؛ کمی بعد دوباره تلاش کنید.");
    e.status = 502;
    throw e;
  }
  clearTimeout(timer);

  if (!res.ok) {
    let detail = "";
    try {
      const body = await res.json();
      detail = body?.error?.message || body?.message || "";
    } catch {
      /* پاسخ غیر JSON */
    }
    console.error(`پشتیبانی AI: خطای ${res.status} از درگاه چابکان`, detail ? `→ ${String(detail).slice(0, 200)}` : "");
    const e = new Error(
      res.status === 401 || res.status === 403
        ? "کلید هوش مصنوعی پذیرفته نشد؛ لطفاً تنظیمات سرور را بررسی کنید."
        : "سرویس هوش مصنوعی موقتاً در دسترس نیست؛ کمی بعد دوباره تلاش کنید."
    );
    e.status = 502;
    throw e;
  }

  const body = await res.json().catch(() => null);
  const reply = body?.choices?.[0]?.message?.content?.toString().trim();
  if (!reply) {
    const e = new Error("پاسخی از دستیار دریافت نشد؛ دوباره تلاش کنید.");
    e.status = 502;
    throw e;
  }
  return { reply: reply.slice(0, 4000) };
}
